"""Shared LLM wrapper for the Business Analytics Portfolio.

Supported providers (checked in this order, via environment variables):
  1. GROQ_API_KEY    -> Groq (free tier)      : OpenAI-compatible endpoint
  2. GEMINI_API_KEY  -> Google Gemini (free tier)
  3. OPENAI_API_KEY  -> OpenAI

If no key is present, every project still runs end-to-end using a
deterministic, rule-based insight engine (see `heuristic_narrative`) so the
portfolio is reproducible offline. Add any one key (e.g. a free Groq key at
https://console.groq.com) and re-run a project's 03_ai_insights.py to get
real LLM-generated narratives.

Design principle (measured AI): the LLM only summarizes numbers that have
already been computed deterministically in Python. It is never allowed to
invent metrics; its job is explanation, prioritization and business
framing.
"""
from __future__ import annotations

import os
from typing import Any

import requests

PROVIDER_ENV = {
    "groq": "GROQ_API_KEY",
    "gemini": "GEMINI_API_KEY",
    "openai": "OPENAI_API_KEY",
}

DEFAULT_MODELS = {
    "groq": "llama-3.3-70b-versatile",
    "gemini": "gemini-2.5-flash",
    "openai": "gpt-4o-mini",
}

ENDPOINTS = {
    "openai": "https://api.openai.com/v1/chat/completions",
    "groq": "https://api.groq.com/openai/v1/chat/completions",
}


def detect_provider() -> tuple[str | None, str]:
    """Return (provider_name, model) or (None, 'offline')."""
    for provider, env in PROVIDER_ENV.items():
        if os.environ.get(env):
            model = os.environ.get(f"{provider.upper()}_MODEL", DEFAULT_MODELS[provider])
            return provider, model
    return None, "offline"


SYSTEM_PROMPT = (
    "You are a senior business analytics consultant writing for an executive "
    "audience. You will receive metrics that were already computed from data. "
    "Never invent numbers: only reference the metrics given. Be concise, "
    "quantitative, decision-oriented and honest about uncertainty. Prefer "
    "bullets over prose."
)


def ask_llm(prompt: str, system: str = SYSTEM_PROMPT, temperature: float = 0.2) -> str:
    """Call the first available provider. Raises RuntimeError if offline."""
    provider, model = detect_provider()
    if provider is None:
        raise RuntimeError(
            "No LLM API key found. Set GROQ_API_KEY (free), GEMINI_API_KEY "
            "or OPENAI_API_KEY to enable LLM narratives."
        )
    if provider == "gemini":
        url = "https://generativelanguage.googleapis.com/v1beta/models"
        key = os.environ["GEMINI_API_KEY"]
        headers = {"x-goog-api-key": key, "Content-Type": "application/json"}
        payload = {
            "contents": [{"role": "user", "parts": [{"text": f"{system}\n\n{prompt}"}]}],
            "generationConfig": {"temperature": temperature},
        }
        resp = requests.post(f"{url}/{model}:generateContent", headers=headers, json=payload, timeout=90)
        resp.raise_for_status()
        data = resp.json()
        return data["candidates"][0]["content"]["parts"][0]["text"]

    resp = requests.post(
        ENDPOINTS[provider],
        headers={
            "Authorization": f"Bearer {os.environ[PROVIDER_ENV[provider]]}",
            "Content-Type": "application/json",
        },
        json={
            "model": os.environ.get(f"{provider.upper()}_MODEL", DEFAULT_MODELS[provider]),
            "temperature": temperature,
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": prompt},
            ],
        },
        timeout=90,
    )
    resp.raise_for_status()
    return resp.json()["choices"][0]["message"]["content"]


# --------------------------------------------------------------------------
# Offline fallback: deterministic narrative engine
# --------------------------------------------------------------------------

def _fmt(v: Any) -> str:
    if isinstance(v, float):
        if abs(v) >= 1000:
            return f"{v:,.0f}"
        if abs(v) >= 1:
            return f"{v:,.1f}"
        return f"{v:.1%}"
    return str(v)


def heuristic_narrative(context: str, metrics: dict[str, Any], drivers: dict[str, str]) -> str:
    """Turn computed metrics into a structured executive narrative.

    context  : e.g. 'Customer churn diagnosis'
    metrics  : {label: computed value} - rendered as a metrics table
    drivers  : {heading: explanation finding} - the analytical storyline
    """
    lines = [f"# {context} - Insight Summary", ""]
    lines.append("*Generated by the deterministic rule-based engine (no LLM key "
                 "set). Run with an API key to get LLM-written commentary over "
                 "these same verified numbers.*")
    lines += ["", "## Key metrics (computed, verified)", ""]
    for k, v in metrics.items():
        lines.append(f"- **{k}:** {_fmt(v)}")
    lines += ["", "## What drives it", ""]
    for heading, finding in drivers.items():
        lines += [f"### {heading}", finding, ""]
    return "\n".join(lines)


def write_insights(path: str, context: str, metrics: dict[str, Any],
                   drivers: dict[str, str], llm_prompt: str | None = None) -> str:
    """Write an insights markdown file. Uses the LLM when a key is available,
    otherwise the deterministic engine. Always embeds the verified metrics.

    Returns the full markdown text.
    """
    provider, _ = detect_provider()
    header = []
    if provider:
        header.append(f"*AI commentary by: **{provider.title()}***")
    else:
        header.append("*AI commentary: offline rule-based engine "
                      "(set GROQ_API_KEY / GEMINI_API_KEY / OPENAI_API_KEY and "
                      "re-run to get LLM commentary).*")

    narrative = None
    fallback_note = ""
    llm_used = False
    if provider and llm_prompt:
        try:
            narrative = ask_llm(llm_prompt)
            llm_used = True
        except Exception as exc:  # network/auth problems -> graceful fallback
            fallback_note = f"_(LLM call failed: {exc.__class__.__name__}; fell back to rule-based engine.)_"
    if not llm_used:
        narrative = heuristic_narrative(context, metrics, drivers)

    md = "\n".join(header) + "\n\n" + narrative + ("\n\n" + fallback_note if fallback_note else "")
    with open(path, "w", encoding="utf-8") as f:
        f.write(md + "\n")
    return md
